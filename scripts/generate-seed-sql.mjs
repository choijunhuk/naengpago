import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { buildSeedDataset, validateSeedDataset } from './seed-data.mjs';

const projectRoot = new URL('..', import.meta.url).pathname;
const seedDirectory = join(projectRoot, 'supabase', 'seed');

function csvCell(value) {
  if (value === null || value === undefined) return '';
  const text = typeof value === 'object' ? JSON.stringify(value) : String(value);
  return `"${text.replaceAll('"', '""')}"`;
}

function toCsv(rows, columns) {
  return [
    columns.join(','),
    ...rows.map((row) => columns.map((column) => csvCell(row[column])).join(','))
  ].join('\n') + '\n';
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value) || typeof value === 'object') {
    return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}

function insertSql(table, columns, rows, transforms = {}) {
  const values = rows.map((row) => `(${columns.map((column) => {
    const value = transforms[column] ? transforms[column](row[column]) : row[column];
    return sqlLiteral(value);
  }).join(', ')})`);
  return `insert into public.${table} (${columns.join(', ')}) values\n${values.join(',\n')}\non conflict do nothing;`;
}

const dataset = buildSeedDataset();
const validation = validateSeedDataset(dataset);
if (validation.errors.length > 0) {
  throw new Error(validation.errors.join('\n'));
}

await mkdir(seedDirectory, { recursive: true });
await Promise.all([
  writeFile(join(seedDirectory, 'ingredient_master.csv'), toCsv(dataset.masters, [
    'id', 'standardNameKo', 'standardNameEn', 'category', 'parentId', 'quantityType',
    'defaultUnit', 'fridge', 'freezer', 'pantry'
  ])),
  writeFile(join(seedDirectory, 'ingredient_aliases.csv'), toCsv(dataset.aliases, [
    'id', 'masterId', 'alias', 'lang', 'source'
  ])),
  writeFile(join(seedDirectory, 'ingredient_substitutions.csv'), toCsv(dataset.substitutions, [
    'id', 'fromMasterId', 'toMasterId', 'bidirectional', 'note'
  ])),
  writeFile(join(seedDirectory, 'recipes.csv'), toCsv(dataset.recipes, [
    'id', 'name', 'imageUrl', 'cookTimeMin', 'difficulty', 'servings', 'caloriesEst',
    'steps', 'tags', 'requiredTools', 'source', 'isActive'
  ])),
  writeFile(join(seedDirectory, 'recipe_ingredients.csv'), toCsv(dataset.recipeIngredients, [
    'id', 'recipeId', 'masterId', 'nameText', 'quantity', 'unit', 'isOptional', 'substitutionGroup'
  ]))
]);

const sql = [
  '-- Generated by scripts/generate-seed-sql.mjs. Do not edit by hand.',
  insertSql('ingredient_master', [
    'id', 'standard_name_ko', 'standard_name_en', 'category', 'parent_id', 'quantity_type',
    'default_unit', 'default_shelf_life_days_fridge', 'default_shelf_life_days_freezer',
    'default_shelf_life_days_pantry'
  ], dataset.masters.map((row) => ({
    id: row.id,
    standard_name_ko: row.standardNameKo,
    standard_name_en: row.standardNameEn,
    category: row.category,
    parent_id: row.parentId,
    quantity_type: row.quantityType,
    default_unit: row.defaultUnit,
    default_shelf_life_days_fridge: row.fridge,
    default_shelf_life_days_freezer: row.freezer,
    default_shelf_life_days_pantry: row.pantry
  }))),
  insertSql('ingredient_aliases', ['id', 'master_id', 'alias', 'lang', 'source'], dataset.aliases.map((row) => ({
    id: row.id, master_id: row.masterId, alias: row.alias, lang: row.lang, source: row.source
  }))),
  insertSql('ingredient_substitutions', ['id', 'from_master_id', 'to_master_id', 'bidirectional', 'note'], dataset.substitutions.map((row) => ({
    id: row.id, from_master_id: row.fromMasterId, to_master_id: row.toMasterId,
    bidirectional: row.bidirectional, note: row.note
  }))),
  insertSql('recipes', [
    'id', 'name', 'image_url', 'cook_time_min', 'difficulty', 'servings', 'calories_est',
    'steps', 'tags', 'required_tools', 'source', 'is_active'
  ], dataset.recipes.map((row) => ({
    id: row.id, name: row.name, image_url: row.imageUrl, cook_time_min: row.cookTimeMin,
    difficulty: row.difficulty, servings: row.servings, calories_est: row.caloriesEst,
    steps: row.steps, tags: row.tags, required_tools: row.requiredTools,
    source: row.source, is_active: row.isActive
  })), {
    tags: (value) => `{${value.join(',')}}`,
    required_tools: (value) => `{${value.join(',')}}`
  }),
  insertSql('recipe_ingredients', [
    'id', 'recipe_id', 'master_id', 'name_text', 'quantity', 'unit', 'is_optional', 'substitution_group'
  ], dataset.recipeIngredients.map((row) => ({
    id: row.id, recipe_id: row.recipeId, master_id: row.masterId, name_text: row.nameText,
    quantity: row.quantity, unit: row.unit, is_optional: row.isOptional,
    substitution_group: row.substitutionGroup
  })))
].join('\n\n') + '\n';

await writeFile(join(projectRoot, 'supabase', 'seed.sql'), sql);
console.log(JSON.stringify({
  masters: dataset.masters.length,
  aliases: dataset.aliases.length,
  substitutions: dataset.substitutions.length,
  recipes: dataset.recipes.length,
  recipeIngredients: dataset.recipeIngredients.length
}));
